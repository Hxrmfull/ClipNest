        ["en"] = All.ToDictionary(s => s.Key, s => s.En),
        ["zh"] = All.ToDictionary(s => s.Key, s => s.Zh),
    };

    /// <summary>The strings of "ru", "en" or "zh".</summary>
    public static Dictionary<string, string> For(string code) => ByLanguage[code];
